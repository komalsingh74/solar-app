import mongoose from "mongoose";
import Employee from "../models/hrms/Employee.js";
import User from "../models/userSchema.js";
import AppError from "../utils/AppError.js";
import asyncHandler from "../utils/asyncHandler.js";

const departments = ["Sales", "Installation", "Service", "Purchase", "Accounts", "HR", "Management", "Other"];
const employmentTypes = ["Full-time", "Part-time", "Contract", "Temporary"];
const shifts = ["General", "Morning", "Evening", "Night"];
const statuses = ["Active", "Inactive", "Resigned", "Terminated"];
const salaryStructures = ["Staff", "Worker", "Contract"];
const fields = [
  "fullName", "phone", "email", "pan", "uan", "joiningDate", "department", "designation",
  "employmentType", "reportsTo", "shift", "systemRole", "status", "electricianLicenseExpiry",
  "heightSafetyTrainingExpiry", "salaryStructure", "monthlyGrossSalary", "bankName", "accountNumber", "ifsc",
];
const validId = mongoose.isValidObjectId;
const populateReportsTo = (query) => query
  .populate("reportsTo", "_id fullName employeeCode designation")
  .populate("reportsToUserId", "_id name");

const asDate = (value, label) => {
  if (value == null || value === "") return null;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) throw new AppError(`Enter a valid ${label}`, 400, "INVALID_DATE");
  return date;
};

const prepareEmployee = async (body, existing) => {
  if (!body || typeof body !== "object" || Array.isArray(body)) {
    throw new AppError("A JSON object is required", 400, "INVALID_BODY");
  }
  if (Object.hasOwn(body, "employeeCode")) {
    throw new AppError("Employee code is generated by the server and cannot be changed", 400, "EMPLOYEE_CODE_READ_ONLY");
  }
  const values = Object.fromEntries(fields.filter((field) => Object.hasOwn(body, field)).map((field) => [field, body[field]]));
  if (!existing || Object.hasOwn(body, "fullName")) {
    if (typeof body.fullName !== "string" || !body.fullName.trim()) throw new AppError("Employee name is required", 400, "REQUIRED_FIELDS");
  }
  if (!existing || Object.hasOwn(body, "phone")) {
    if (typeof body.phone !== "string" || !body.phone.trim()) throw new AppError("Employee phone is required", 400, "REQUIRED_FIELDS");
  }
  if (Object.hasOwn(body, "department") && !departments.includes(body.department)) throw new AppError("Choose a valid department", 400, "INVALID_DEPARTMENT");
  if (Object.hasOwn(body, "employmentType") && !employmentTypes.includes(body.employmentType)) throw new AppError("Choose a valid employment type", 400, "INVALID_EMPLOYMENT_TYPE");
  if (Object.hasOwn(body, "shift") && !shifts.includes(body.shift)) throw new AppError("Choose a valid shift", 400, "INVALID_SHIFT");
  if (Object.hasOwn(body, "status") && !statuses.includes(body.status)) throw new AppError("Choose a valid employee status", 400, "INVALID_STATUS");
  if (Object.hasOwn(body, "salaryStructure") && !salaryStructures.includes(body.salaryStructure)) throw new AppError("Choose a valid salary structure", 400, "INVALID_SALARY_STRUCTURE");
  if (Object.hasOwn(body, "joiningDate")) values.joiningDate = asDate(body.joiningDate, "joining date");
  if (Object.hasOwn(body, "electricianLicenseExpiry")) values.electricianLicenseExpiry = asDate(body.electricianLicenseExpiry, "licence expiry date");
  if (Object.hasOwn(body, "heightSafetyTrainingExpiry")) values.heightSafetyTrainingExpiry = asDate(body.heightSafetyTrainingExpiry, "training expiry date");
  if (Object.hasOwn(body, "monthlyGrossSalary")) {
    const salary = Number(body.monthlyGrossSalary);
    if (!Number.isFinite(salary) || salary < 0) throw new AppError("Monthly gross salary must be a non-negative number", 400, "INVALID_SALARY");
    values.monthlyGrossSalary = salary;
  }
  if (Object.hasOwn(body, "reportsTo")) {
    if (body.reportsTo && !validId(body.reportsTo)) throw new AppError("Choose a valid reporting employee", 400, "INVALID_REPORTS_TO");
    if (body.reportsTo && String(body.reportsTo) === String(existing?._id)) throw new AppError("An employee cannot report to themselves", 400, "INVALID_REPORTS_TO");
    const unchangedManager = existing && String(body.reportsTo || "") === String(existing.reportsTo || "");
    if (body.reportsTo && !unchangedManager && !await Employee.exists({ _id: body.reportsTo, status: "Active" })) {
      throw new AppError("Choose an active reporting employee", 400, "INVALID_REPORTS_TO");
    }
    values.reportsTo = body.reportsTo || null;
    values.reportsToUserId = null;
  }
  return values;
};

const duplicateCodeError = (error) => error?.code === 11000
  && (error.keyPattern?.employeeCode || String(error.message).includes("employeeCode"));

export const employeeOptions = asyncHandler(async (_req, res) => {
  const employees = await Employee.find({ status: "Active" })
    .select("_id fullName employeeCode designation department systemRole status")
    .sort({ fullName: 1, _id: 1 })
    .lean();
  res.json({ success: true, data: { employees } });
});

export const listEmployees = asyncHandler(async (req, res) => {
  const page = Math.max(1, Number.parseInt(req.query.page, 10) || 1);
  const limit = Math.min(100, Math.max(1, Number.parseInt(req.query.limit, 10) || 20));
  const filter = {};
  if (statuses.includes(req.query.status)) filter.status = req.query.status;
  if (departments.includes(req.query.department)) filter.department = req.query.department;
  if (typeof req.query.q === "string" && req.query.q.trim()) {
    const escaped = req.query.q.trim().replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const expression = new RegExp(escaped, "i");
    filter.$or = ["fullName", "employeeCode", "phone", "email", "designation"].map((field) => ({ [field]: expression }));
  }
  const [items, total] = await Promise.all([
    populateReportsTo(Employee.find(filter).sort({ fullName: 1, _id: 1 }).skip((page - 1) * limit).limit(limit)).lean(),
    Employee.countDocuments(filter),
  ]);
  res.json({ success: true, data: { items, pagination: { page, limit, total, pages: Math.ceil(total / limit) } } });
});

export const createEmployee = asyncHandler(async (req, res) => {
  const values = await prepareEmployee(req.body, null);
  const email = typeof values.email === "string" ? values.email.trim().toLowerCase() : "";
  const linkedUser = email
    ? await User.findOne({ email }).select("_id employeeId")
    : null;
  let item;
  try {
    item = await Employee.create(values);
  } catch (error) {
    if (duplicateCodeError(error)) throw new AppError("Employee code conflict. Please retry employee creation.", 409, "EMPLOYEE_CODE_CONFLICT");
    throw error;
  }
  if (linkedUser && !linkedUser.employeeId) {
    try {
      await User.updateOne({ _id: linkedUser._id, employeeId: null }, { $set: { employeeId: item._id } });
    } catch (error) {
      await item.deleteOne();
      throw error;
    }
  }
  const populated = await populateReportsTo(Employee.findById(item._id));
  res.status(201).json({ success: true, data: { item: populated } });
});

export const updateEmployee = asyncHandler(async (req, res) => {
  if (!validId(req.params.id)) throw new AppError("Invalid employee ID", 400, "INVALID_ID");
  const item = await Employee.findById(req.params.id);
  if (!item) throw new AppError("Employee not found", 404, "EMPLOYEE_NOT_FOUND");
  Object.assign(item, await prepareEmployee(req.body, item));
  try {
    await item.save();
  } catch (error) {
    if (duplicateCodeError(error)) throw new AppError("Employee code conflict. The code cannot be changed.", 409, "EMPLOYEE_CODE_CONFLICT");
    throw error;
  }
  const populated = await populateReportsTo(Employee.findById(item._id));
  res.json({ success: true, data: { item: populated } });
});

export const deactivateEmployee = asyncHandler(async (req, res) => {
  if (!validId(req.params.id)) throw new AppError("Invalid employee ID", 400, "INVALID_ID");
  const item = await Employee.findByIdAndUpdate(
    req.params.id,
    { $set: { status: "Inactive" } },
    { returnDocument: "after", runValidators: true },
  );
  if (!item) throw new AppError("Employee not found", 404, "EMPLOYEE_NOT_FOUND");
  res.json({ success: true, data: { id: item._id, employeeCode: item.employeeCode, status: item.status } });
});
