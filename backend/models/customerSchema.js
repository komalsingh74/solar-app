
import mongoose from "mongoose";

const { Schema, model, models } = mongoose;

// 1. Customer address
const addressSchema = new Schema(
  {
    address: {
      type: String,
      trim: true,
      default: "",
    },
    city: {
      type: String,
      trim: true,
      default: "",
    },
    state: {
      type: String,
      trim: true,
      default: "Uttar Pradesh",
    },
    pincode: {
      type: String,
      trim: true,
      default: "",
    },
  },
  { _id: false }
);

// 2. Solar installation site data
const siteDataSchema = new Schema(
  {
    electricityConsumerNumber: {
      type: String,
      trim: true,
      default: "",
    },
    discom: {
      type: String,
      trim: true,
      default: "",
    },
    sanctionedLoad: {
      type: Number,
      min: 0,
      default: null,
    },
    sanctionedLoadUnit: {
      type: String,
      enum: ["kW", "kVA"],
      default: "kW",
    },
    roofType: {
      type: String,
      trim: true,
      default: "",
    },
  },
  { _id: false }
);

// 3. Customer documents
const documentSchema = new Schema(
  {
    documentName: {
      type: String,
      required: true,
      trim: true,
    },
    documentType: {
      type: String,
      enum: [
        "PAN_CARD",
        "GST_CERTIFICATE",
        "ELECTRICITY_BILL",
        "SIGNED_QUOTATION",
        "AADHAAR",
        "OTHER",
      ],
      default: "OTHER",
    },
    fileUrl: {
      type: String,
      default: "",
      trim: true,
    },
    publicId: {
      type: String,
      default: "",
      trim: true,
    },
    originalFileName: {
      type: String,
      default: "",
      trim: true,
    },
    mimeType: {
      type: String,
      default: "",
    },
    fileSize: {
      type: Number,
      min: 0,
      default: null,
    },
    status: {
      type: String,
      enum: ["Missing", "Uploaded", "Pending", "Verified", "Rejected"],
      default: "Missing",
    },
    uploadedAt: {  
      type: Date,
      default: null,
    },
    verifiedAt: {
      type: Date,
      default: null,
    },
    remarks: {
      type: String,
      trim: true,
      default: "",
    },
    isRequired: {
      type: Boolean,
      default: false,
    },
  },
  { timestamps: true }
);

// 4. Main Customer Schema
const customerSchema = new Schema(
  {
    // Generated by the backend, e.g. CUS-001
    customerId: {
      type: String,
      required: true,
      trim: true,
    },

    // Details tab
    customerType: {
      type: String,
      enum: [
        "Residential",
        "Commercial",
        "Industrial",
        "Government",
      ],
      required: true,
      default: "Residential",
    },

    customerName: {
      type: String,
      required: true,
      trim: true,
    },

    contactPerson: {
      type: String,
      trim: true,
      default: "",
    },

    phone: {
      type: String,
      required: true,
      trim: true,
    },

    email: {
      type: String,
      trim: true,
      lowercase: true,
      default: "",
    },

    gstin: {
      type: String,
      trim: true,
      uppercase: true,
      default: "",
    },

    pan: {
      type: String,
      trim: true,
      uppercase: true,
      default: "",
    },

    status: {
      type: String,
      enum: ["Active", "Inactive"],
      default: "Active",
    },

    // Address tab
    installationAddress: {
      type: addressSchema,
      default: () => ({}),
    },

    billingSameAsInstallation: {
      type: Boolean,
      default: true,
    },

    billingAddress: {
      type: addressSchema,
      default: () => ({}),
    },

    // Site Data tab
    siteData: {
      type: siteDataSchema,
      default: () => ({}),
    },

    // Docs tab
    documents: {
      type: [documentSchema],
      default: [],
    },

    customDocumentTypes: {
      type: [String],
      default: [],
    },

    // Future module connections
    createdBy: {
      type: Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },

    updatedBy: {
      type: Schema.Types.ObjectId,
      ref: "User",
      default: null,
    },

    notes: {
      type: String,
      trim: true,
      default: "",
    },
  },
  {
    timestamps: true,
    versionKey: false,
  }
);

// Customer IDs are unique across this single-tenant application.
customerSchema.index({ customerId: 1 }, { unique: true });

// Common customer searches
customerSchema.index({ customerName: 1 });
customerSchema.index({ phone: 1 });
customerSchema.index({ status: 1 });

const Customer =
  models.Customer || model("Customer", customerSchema);

export default Customer;
